//! Natives registered from Rust types (`NativeRegistry::function`), generated declarations, and typed opaque
//! handles. Like a real host, these tests use only `lamlet::embed`.

use lamlet::embed::*;
use std::cell::Cell;
use std::rc::Rc;

struct Tree {
    name: String,
    height: f64,
    felled: Rc<Cell<u32>>,
}

impl NativeType for Tree {
    const TYPE_ID: &'static str = "host.garden/tree";
}

impl Drop for Tree {
    fn drop(&mut self) {
        self.felled.set(self.felled.get() + 1);
    }
}

/// A synthetic host: a garden of opaque trees, pure counting functions, and a guarded runtime function.
fn engine(felled: Rc<Cell<u32>>) -> Engine {
    let mut e = Engine::new();
    let r = e.natives_mut();
    r.opaque::<Tree>().unwrap();
    r.function("host.garden/plant", move |_, (name, height): (String, f64)| Ok(Opaque::new(Tree { name, height, felled: felled.clone() })))
        .doc("Fn([String, Float], Tree). Plants a tree.")
        .register()
        .unwrap();
    r.function("host.garden/describe", |_, (t,): (Opaque<Tree>,)| Ok(format!("{} ({} m)", t.name, t.height)))
        .register()
        .unwrap();
    r.function("host.counts/leaves", |_, (name,): (String,)| match name.as_str() {
        "oak" => Ok(42_289i64),
        other => Err(format!("no tree named {:?}", other)),
    })
    .pure()
    .doc("Fn([String], Int). Leaves on a named tree;\ncounting costs $1.")
    .register()
    .unwrap();
    r.function("host.counts/summary", |_, (xs, label): (Vec<i64>, Option<String>)| Ok((xs.iter().sum::<i64>(), label.is_some())))
        .pure()
        .register()
        .unwrap();
    r.function("host.clock/seconds", |ctx, ()| ctx.input_as::<f64>("clock")).register().unwrap();
    r.function("host.vault/secret", |_, ()| Ok("s3cret".to_string())).capability("vault").register().unwrap();
    e
}

fn host_engine() -> (Engine, Rc<Cell<u32>>) {
    let felled = Rc::new(Cell::new(0));
    let mut e = engine(felled.clone());
    let package = e.natives().declarations("host").unwrap();
    let mut resolver = MemoryResolver::new();
    resolver.add("host", &package, Exports::All);
    e.set_resolver(resolver);
    (e, felled)
}

#[test]
fn signatures_come_from_rust_types() {
    let e = engine(Rc::new(Cell::new(0)));
    let summary = &e.natives().entries["host.counts/summary"];
    let option = TypeDesc::Variant(vec![("none".into(), TypeDesc::Unit), ("some".into(), TypeDesc::String)]);
    assert_eq!(summary.params, vec![TypeDesc::List(TypeDesc::Int.into()), option]);
    assert_eq!(summary.ret, TypeDesc::Record(vec![("first".into(), TypeDesc::Int), ("second".into(), TypeDesc::Bool)]));
    assert_eq!(summary.availability, Availability::Pure);
    let plant = &e.natives().entries["host.garden/plant"];
    assert_eq!(plant.ret, TypeDesc::Opaque("host.garden/tree".into()));
    assert_eq!(plant.availability, Availability::Runtime);
    assert_eq!(e.natives().entries["host.vault/secret"].capabilities, ["vault"]);
}

#[test]
fn declarations_are_a_checked_lamlet_package() {
    let e = engine(Rc::new(Cell::new(0)));
    let package = e.natives().declarations("host").unwrap();
    assert_eq!(
        package,
        r#"Native interface for `host`, generated by `NativeRegistry::declarations`. Regenerate it instead of editing it.

$[Import std]

$[NativeType Tree "host.garden/tree"]

$[Native seconds {std::Fn {'} std::Float} "host.clock/seconds" Runtime]

Fn([String], Int). Leaves on a named tree;
counting costs $$1.
$[Native leaves {std::Fn {' std::String} std::Int} "host.counts/leaves" Pure]

$[Native summary {std::Fn {' {std::List std::Int} {std::Variant {' {std::Field "none" std::Unit} {std::Field "some" std::String}}}} {std::Struct {' {std::Field "first" std::Int} {std::Field "second" std::Bool}}}} "host.counts/summary" Pure]

$[Native describe {std::Fn {' Tree} std::String} "host.garden/describe" Runtime]

Fn([String, Float], Tree). Plants a tree.
$[Native plant {std::Fn {' std::String std::Float} Tree} "host.garden/plant" Runtime]

$[Native secret {std::Fn {'} std::String} "host.vault/secret" Runtime]
"#
    );
    // A prefix selects part of the registry.
    let counts = e.natives().declarations("host.counts").unwrap();
    assert!(counts.contains("leaves") && !counts.contains("plant") && !counts.contains("NativeType"));
}

#[test]
fn documents_import_the_generated_package() {
    let (e, _) = host_engine();
    let doc = e.check(SourceFile::new("g.lam", "$[Import* std]$[Import* host]$[# n [% {leaves \"oak\"}]]Leaves: $n.")).unwrap();
    assert_eq!(doc.render(text).unwrap(), "Leaves: 42289.");
    assert_eq!(doc.doc("leaves"), Some("Fn([String], Int). Leaves on a named tree;\ncounting costs $1."));
    // The same package checks at build time, against metadata only.
    let doc = e.check_interface(SourceFile::new("g.lam", "$[Import* std]$[Import* host]${describe {plant \"oak\" 12.5}}")).unwrap();
    assert!(doc.parts().iter().any(|p| matches!(p, Part::Region { value: None, .. })));
}

#[test]
fn typed_natives_run_with_converted_arguments() {
    let (e, _) = host_engine();
    let doc = e
        .check(SourceFile::new(
            "g.lam",
            "$[Import* std]$[Import* host]$[# s [% {summary {' 1 2 3} {some \"x\"}}]]$[# at {^ {} {seconds}}]$[# tall {^ {h} {describe {plant \"oak\" h}}}]",
        ))
        .unwrap();
    let s = doc.binding("s").unwrap();
    assert_eq!(display(&s.value), "{first: 6, second: true}");
    let mut inst = e.instance(&doc).unwrap();
    inst.set_input("clock", 2.5).unwrap();
    assert_eq!(inst.call_typed::<_, f64>(&doc.binding("at").unwrap(), ()).unwrap(), 2.5);
    assert_eq!(inst.call_typed::<_, String>(&doc.binding("tall").unwrap(), (12.5,)).unwrap(), "oak (12.5 m)");
}

#[test]
fn opaque_values_are_typed_handles_released_when_unused() {
    let (e, felled) = host_engine();
    let doc = e.check(SourceFile::new("g.lam", "$[Import* std]$[Import* host]$[# grow {^ {} {plant \"elm\" 3.0}}]")).unwrap();
    let mut inst = e.instance(&doc).unwrap();
    let tree: Opaque<Tree> = inst.call_typed(&doc.binding("grow").unwrap(), ()).unwrap();
    assert_eq!((tree.name.as_str(), tree.height), ("elm", 3.0));
    let as_value = tree.clone().into_lamlet().unwrap();
    assert!(Data::from_value(&as_value).unwrap_err().contains("host.garden/tree"));
    assert!(<Opaque<Tree>>::from_lamlet(&Value::Int(1)).is_err());
    drop((tree, as_value));
    inst.reset();
    assert_eq!(felled.get(), 1);
}

#[test]
fn native_failures_name_the_api_and_the_calling_region() {
    let (e, _) = host_engine();
    // During preparation the failure is a check error.
    let err = e.check(SourceFile::new("g.lam", "$[Import* std]$[Import* host]\n$[# n [% {leaves \"fir\"}]]")).unwrap_err();
    assert!(err.to_string().contains("native `host.counts/leaves` failed: no tree named \"fir\""), "{}", err);
    assert_eq!(err.locations()[0].as_ref().unwrap().line, 2);
    // At runtime it is a runtime error, positioned at the call.
    let doc = e.check(SourceFile::new("g.lam", "$[Import* std]$[Import* host]\n$[# count {^ {name} {leaves name}}]")).unwrap();
    let mut inst = e.instance(&doc).unwrap();
    let err = inst.call_typed::<_, i64>(&doc.binding("count").unwrap(), ("fir",)).unwrap_err();
    assert_eq!(err.kind(), ErrorKind::Runtime);
    assert!(err.to_string().contains("host.counts/leaves"), "{}", err);
    assert_eq!(err.locations()[0].as_ref().unwrap().line, 2);
    // A missing input is reported by the native.
    let doc = e.check(SourceFile::new("g.lam", "$[Import* std]$[Import* host]$[# at {^ {} {seconds}}]")).unwrap();
    let err = e.instance(&doc).unwrap().call_typed::<_, f64>(&doc.binding("at").unwrap(), ()).unwrap_err();
    assert!(err.to_string().contains("host input \"clock\" is not provided"), "{}", err);
}

#[test]
fn capabilities_are_checked_per_instance() {
    let (e, _) = host_engine();
    let doc = e.check(SourceFile::new("g.lam", "$[Import* std]$[Import* host]$[# peek {^ {} {secret}}]")).unwrap();
    let peek = doc.binding("peek").unwrap();
    let mut inst = e.instance(&doc).unwrap();
    assert!(inst.call_typed::<_, String>(&peek, ()).unwrap_err().to_string().contains("capability \"vault\""));
    inst.grant("vault");
    assert_eq!(inst.call_typed::<_, String>(&peek, ()).unwrap(), "s3cret");
}

#[test]
fn registration_errors_are_reported() {
    let mut r = NativeRegistry::new();
    r.function("host.a/x", |_, ()| Ok(1i64)).register().unwrap();
    let err = r.function("host.a/x", |_, ()| Ok(2i64)).register().unwrap_err();
    assert_eq!(err.kind(), ErrorKind::Registry);
    // An opaque type must be registered before a signature uses it.
    let err = r.function("host.a/t", |_, ()| Ok(Opaque::new(Leaf))).register().unwrap_err();
    assert!(err.to_string().contains("not registered"), "{}", err);
    // Two ids that would produce the same Lamlet name.
    r.function("host.b/x", |_, ()| Ok(1i64)).register().unwrap();
    assert!(r.declarations("host").unwrap_err().to_string().contains("both be declared as `x`"));
}

struct Leaf;
impl NativeType for Leaf {
    const TYPE_ID: &'static str = "host.a/leaf";
}
